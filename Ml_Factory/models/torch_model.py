import torch
import torch.nn as nn
from torch.nn.modules import Conv2d, ReLU

"""

We are defining two models here:

    ModelOneGen: Generator
    ModelFighter: Discriminator

    I am Following the GAN's Model where:
        We send images from two different sources, one is the real image, other is generated by Generator (ModelOneGen)
        Discrimintors Job is to correctly classify the real image as true(real) and generated image as false(fake)

        
    Therefore,
        Generator and Discriminator in this case will be CNNs (Convolutional Neural Network)
        Generator will take an grayscale image as input and output rgb image 
        Discriminator will take rgb image and decide which one is fake or real

        Here the goal will be to min max, where generator is trying to maximize its goal of being identified as the real image
        While the discriminator is trying to minimize the loss by classifying generated image as real

        

"""

class ModelOneGen(nn.Module):
    """
        ModelOneGen: Better ModelOne

        Going to use UNet architecture; for auto colorization....
        
    """
    def __init__(self):
        
        super(ModelOneGen,self).__init__()

        # Encoders
        self.e1 = self.encoder_block(1,64)
        self.e2 = self.encoder_block(64, 128)
        self.e3 = self.encoder_block(128, 256)
        self.e4 = self.encoder_block(256,512)
        self.e5 = self.encoder_block(512, 1024)
        self.e6 = self.encoder_block(1024,2048)

        # Decoders
        self.u5 = self.up_block(2048, 1024)
        self.d5 = self.decoder_block(2048, 1024)
        
        self.u4 = self.up_block(1024, 512)
        self.d4 = self.decoder_block(1024, 512)

        self.u3 = self.up_block(512, 256)
        self.d3 = self.decoder_block(512, 256)

        self.u2 = self.up_block(256, 128)
        self.d2 = self.decoder_block(256, 128)
        
        self.u1 = self.up_block(128, 64)
        self.d1 = self.decoder_block(128, 64)

        self.final = nn.Conv2d(64, 3, kernel_size=1)
        self.tanh = nn.Tanh()

    def forward(self, x):
        e1 = self.e1(x)
        e2 = self.e2(e1)
        e3 = self.e3(e2)
        e4 = self.e4(e3)
        e5 = self.e5(e4)
        e6 = self.e6(e5)

        d5 = self.u5(e6)
        d5 = torch.cat((e5, d5), dim=1)
        d5 = self.d5(d5)

        d4 = self.u4(d5)
        d4 = torch.cat((e4, d4), dim=1)
        d4 = self.d4(d4)

        d3 = self.u3(d4)
        d3 = torch.cat((e3, d3), dim=1)
        d3 = self.d3(d3)

        d2 = self.u2(d3)
        d2 = torch.cat((e2, d2), dim=1)
        d2 = self.d2(d2)
        
        d1 = self.u1(d2)
        d1 = torch.cat((e1, d1), dim=1)
        d1 = self.d1(d1)       


        out = self.final(d1)

        return self.tanh(out)

    def encoder_block(self, input_shape: int, output_shape: int):
        return nn.Sequential(
                nn.Conv2d(input_shape, output_shape, kernel_size=3, padding=1),
                nn.ReLU(),
                nn.Conv2d(output_shape, output_shape, kernel_size=3, padding=1),
                nn.ReLU(),
                nn.MaxPool2d(2)
                )
    
    def up_block(self, input_shape: int, output_shape: int):
        return nn.ConvTranspose2d(input_shape, output_shape, kernel_size=2, stride=2)

    def decoder_block(self, input_shape: int, output_shape: int):
        return nn.Sequential(
                nn.Conv2d(input_shape, output_shape, kernel_size=3, padding=1),
                nn.ReLU(),
                nn.Conv2d(output_shape, output_shape, kernel_size=3, padding=1),
                nn.ReLU(),
                )


