class ModelOneGenX(nn.Module):
    def __init__(self):
        super(ModelOneGenX, self).__init__()

        self.blocks = (1, 32, 64, 128, 256, 512)
            
        self.encoders = nn.ModuleList([
            self.encoder_block(self.blocks[i], self.blocks[i+1]) for i in range(len(self.blocks)-1)
            ])
        
        self.b = self.bottleneck(self.blocks[-1],self.blocks[-1])

        self.decoders = nn.ModuleList([
            self.decoder_block(self.blocks[i] * 2, self.blocks[i-1]) for i in range(len(self.blocks)-1, 1, -1)
            ])
        self.final = self.final_block(64,3)

        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        
        skip_connections = []

        for encoder in self.encoders:
            x = encoder(x)
            skip_connections.append(x)


        x = self.b(x)

        for decoder, skip in zip(self.decoders, reversed(skip_connections)):
            x = torch.cat([x, skip], dim=1)
            x = decoder(x)

        x = torch.cat([x, skip_connections[0]], dim=1)
        x = self.final(x)

        return x


    def encoder_block(self, in_channel: int, out_channel: int, groups: int = 8):
        return nn.Sequential(
                nn.Conv2d(in_channel, out_channel, kernel_size=3, padding=1, stride=1),
                nn.InstanceNorm2d(out_channel),
                nn.LeakyReLU(0.2, inplace=True),

                nn.Conv2d(out_channel, out_channel, kernel_size=3, padding=1, stride=1),
                nn.InstanceNorm2d(out_channel),
                nn.LeakyReLU(0.2, inplace=True),

                nn.MaxPool2d(2)
                )
    
    def bottleneck(self, in_channel: int, out_channel: int):
        return nn.Sequential(
                nn.Conv2d(in_channel, out_channel, kernel_size=3, padding=1),
                nn.Tanh()
                )

    def decoder_block(self, in_channel: int, out_channel: int, groups: int = 8):
        return nn.Sequential(
                nn.ConvTranspose2d(in_channel, out_channel, kernel_size=3, stride=2, padding=1,output_padding=1),
                nn.BatchNorm2d(out_channel),
                nn.ReLU(),
                nn.ConvTranspose2d(out_channel, out_channel, kernel_size=3, padding=1),
                nn.BatchNorm2d(out_channel),
                nn.ReLU()
                )
    
    def final_block(self, in_channel: int, out_channel: int):
        return nn.Sequential(
                nn.ConvTranspose2d(in_channel, out_channel, kernel_size=3, stride=2, padding=1,output_padding=1),
                nn.ReLU(),
                nn.ConvTranspose2d(out_channel, out_channel, kernel_size=3, stride=1, padding=1),
                nn.Tanh()
                )

class ModelFighter2(nn.Module):
    def __init__(self):
        super(ModelFighter2, self).__init__()

        self.groups = 8
        self.model = nn.Sequential(
                           # First convolutional layer
            nn.Conv2d(3, 64, kernel_size=4, stride=2, padding=1),  # Output size: (batch, 64, h/2, w/2)
            nn.LeakyReLU(0.2, inplace=True),  # Leaky ReLU activation function
            # Second convolutional layer
            nn.Conv2d(64, 128, kernel_size=4, stride=2, padding=1),  # Output size: (batch, 128, h/4, w/4)
            nn.GroupNorm(self.groups,128),  # Batch Normalization
            nn.LeakyReLU(0.2, inplace=True),
            
            # Third convolutional layer
            nn.Conv2d(128, 256, kernel_size=4, stride=2, padding=1),  # Output size: (batch, 256, h/8, w/8)
            nn.GroupNorm(self.groups,256),
            nn.LeakyReLU(0.2, inplace=True),
            
            # Fourth convolutional layer
            nn.Conv2d(256, 512, kernel_size=4, stride=2, padding=1),  # Output size: (batch, 512, h/16, w/16)
            nn.GroupNorm(self.groups,512),
            nn.LeakyReLU(0.2, inplace=True),
            
            # Fifth convolutional layer
            nn.Conv2d(512, 1, kernel_size=4, stride=2, padding=1),  # Output size: (batch, 1, h/32, w/32)
                )

    def forward(self,x):
        return self.model(x)


